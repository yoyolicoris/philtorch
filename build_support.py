import os


def resolve_cuda_build(
    force_cuda_value,
    cuda_home,
    cuda_available,
    cuda_arch_list=None,
    torch_cuda_version=None,
):
    # An empty value means unset, e.g. a GitHub Actions expression for a
    # missing input or `docker run -e PHILTORCH_FORCE_CUDA=`.
    if force_cuda_value not in {"", "0", "1"}:
        raise RuntimeError(
            f"PHILTORCH_FORCE_CUDA must be either '0' or '1'; got {force_cuda_value!r}."
        )

    force_cuda = force_cuda_value == "1"
    if force_cuda and cuda_home is None:
        raise RuntimeError(
            "PHILTORCH_FORCE_CUDA=1 was requested, but CUDA_HOME is not set "
            "or the CUDA toolkit could not be found."
        )
    if force_cuda and torch_cuda_version is None:
        raise RuntimeError(
            "PHILTORCH_FORCE_CUDA=1 was requested, but the installed PyTorch has "
            "no CUDA support (torch.version.cuda is None). Install a CUDA build "
            "of PyTorch."
        )
    if force_cuda and not cuda_available and (not cuda_arch_list or cuda_arch_list == "native"):
        raise RuntimeError(
            "PHILTORCH_FORCE_CUDA=1 was requested on a host with no visible GPU, "
            "but TORCH_CUDA_ARCH_LIST is unset or 'native', so there is no safe "
            "target architecture to infer. Set TORCH_CUDA_ARCH_LIST to the target "
            'architectures, e.g. TORCH_CUDA_ARCH_LIST="8.0 8.6".'
        )

    return cuda_home is not None and (force_cuda or cuda_available)


# The oldest torch that builds the Metal source, compiled on macOS alone, whose
# API it is held to (TORCH_TARGET_VERSION, generated by write_metal_headers).
MIN_TORCH_MACOS = "2.10"


def torch_requirements(pinned_torch_version=""):
    # A wheel's compiled extension only works with the PyTorch minor it was
    # built against. Source builds and the CPU wheels keep the broad range;
    # CUDA wheels set PHILTORCH_TORCH_PIN to the torch they were built with.
    if not pinned_torch_version:
        # 2.6 is the first whose BuildExtension builds with py_limited_api.
        return [
            'torch >= 2.6.0; sys_platform != "darwin"',
            f'torch >= {MIN_TORCH_MACOS}.0; sys_platform == "darwin"',
        ]
    parts = pinned_torch_version.split(".")
    if len(parts) != 3 or not all(part.isdigit() for part in parts):
        raise RuntimeError(
            "PHILTORCH_TORCH_PIN must be an exact X.Y.Z torch version; "
            f"got {pinned_torch_version!r}."
        )
    return [f"torch == {parts[0]}.{parts[1]}.*"]


# The raw string delimiter of the generated Metal headers.
_METAL_DELIMITER = "METAL"


def metal_header(source_path):
    """A C++ header that holds the Metal source at ``source_path`` as a raw
    string, named after the file: ``scalar_recur_mps.metal`` becomes
    ``SCALAR_RECUR_MPS_METAL``. torch's Metal shim compiles only from source
    text, so the extension carries the text itself."""
    name = os.path.basename(source_path)
    with open(source_path, encoding="utf-8") as file:
        text = file.read()
    if f'){_METAL_DELIMITER}"' in text:
        raise RuntimeError(f'{name} contains the raw string delimiter ){_METAL_DELIMITER}"')
    variable = name.replace(".", "_").upper()
    return (
        f"// Generated by setup.py from {name}; edit that file instead.\n"
        "#pragma once\n\n"
        f'constexpr const char *{variable} = R"{_METAL_DELIMITER}({text}){_METAL_DELIMITER}";\n'
    )


def target_version_header(version):
    """A C++ header that sets TORCH_TARGET_VERSION to torch ``version``,
    "X.Y", packed as torch packs it, which holds the sources including it
    before any torch header to that version's API."""
    major, minor = version.split(".")
    return (
        "// Generated by setup.py from build_support.MIN_TORCH_MACOS.\n"
        "#pragma once\n\n"
        f"#define TORCH_TARGET_VERSION (((0ULL + {major}) << 56) | ((0ULL + {minor}) << 48))\n"
    )


def _write_if_changed(path, text):
    # Rewriting an unchanged header would rebuild the sources including it.
    if os.path.exists(path):
        with open(path, encoding="utf-8") as file:
            if file.read() == text:
                return
    with open(path, "w", encoding="utf-8") as file:
        file.write(text)


def write_metal_headers(source_dir, include_dir):
    """Writes ``<name>.metal.h`` in ``include_dir`` for each ``.metal`` file in
    ``source_dir``, and ``torch_target_version.h`` for ``MIN_TORCH_MACOS``,
    rewriting only those that changed."""
    os.makedirs(include_dir, exist_ok=True)
    _write_if_changed(
        os.path.join(include_dir, "torch_target_version.h"),
        target_version_header(MIN_TORCH_MACOS),
    )
    for name in sorted(os.listdir(source_dir)):
        if name.endswith(".metal"):
            _write_if_changed(
                os.path.join(include_dir, f"{name}.h"),
                metal_header(os.path.join(source_dir, name)),
            )
